export function overallImpact(c: string, i: string, a: string): Impact {
  const r = Math.max(IMPACT_RANK[c as Impact] ?? 0, IMPACT_RANK[i as Impact] ?? 0, IMPACT_RANK[a as Impact] ?? 0);
  return (['low','moderate','high'] as Impact[])[r];
}

export function baselineFor(impact: Impact): BaselineControl[] {
  const rank = IMPACT_RANK[impact];
  return CATALOG.filter(c => IMPACT_RANK[c.minImpact] <= rank);
}
